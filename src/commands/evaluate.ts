import { evaluateJob, type JobEvaluation } from '../ai/insight.js';
import { AiQuotaError, type ChatClient } from '../ai/models.js';
import { FIT_PREFIX } from '../domain/labels.js';
import { extractFullDescription } from '../github/issue-body.js';
import { addLabels, removeLabel } from '../github/labels.js';
import type { Context } from './context.js';

export interface CommentEvent {
  action?: string;
  issue?: {
    number: number;
    title: string;
    body: string | null;
    labels?: Array<{ name: string } | string>;
    pull_request?: unknown;
  };
  comment?: { body?: string; author_association?: string };
}

export interface EvaluateOptions {
  ai?: { client: ChatClient; profile: string };
}

const COMMAND = /^\s*\/evaluate\b/i;
/** Only the people who run the repository may spend the AI quota. */
const TRUSTED = new Set(['OWNER', 'MEMBER', 'COLLABORATOR']);

function render(evaluation: JobEvaluation, model: string): string {
  const list = (items: string[], ordered = false) =>
    items.length === 0 ? '_Nothing to note._' : items.map((item, index) => `${ordered ? `${index + 1}.` : '-'} ${item}`).join('\n');
  return [
    `## Evaluation: fit ${evaluation.fit}/5`,
    evaluation.summary,
    '### Strengths',
    list(evaluation.strengths),
    '### Gaps and doubts',
    list(evaluation.gaps),
    '### Likely interview questions',
    list(evaluation.interview_questions, true),
    `_Generated by ${model} through GitHub Models from the posting and your profile. Check it before relying on it._`,
  ]
    .filter((part) => part !== '')
    .join('\n\n');
}

/** Pulls the company and role out of a `[Company] Role` title. */
function splitTitle(title: string): { company: string; role: string } {
  const match = /^\[([^\]]+)\]\s*(.+)$/.exec(title);
  return match ? { company: match[1]!, role: match[2]! } : { company: 'the company', role: title };
}

/** The posting text the issue keeps: the collapsed full description, or else the quoted excerpt. */
function descriptionOf(body: string | null): string {
  const full = extractFullDescription(body);
  if (full) return full;
  return (body ?? '')
    .split('\n')
    .filter((line) => line.startsWith('> '))
    .map((line) => line.slice(2))
    .join('\n');
}

/**
 * `/evaluate` comment on a job issue: a full analysis (strengths, gaps, likely interview questions)
 * posted as a comment, with the issue's `fit:*` label refreshed to match. See "Optional AI" in docs/DESIGN.md.
 */
export async function evaluate(ctx: Context, event: CommentEvent, options: EvaluateOptions = {}): Promise<void> {
  const issue = event.issue;
  if (event.action !== 'created' || !issue || issue.pull_request || !COMMAND.test(event.comment?.body ?? '')) {
    ctx.log.info('Not an "/evaluate" comment on an issue; nothing to do');
    return;
  }
  if (!TRUSTED.has(event.comment?.author_association ?? '')) {
    ctx.log.info(`Issue #${issue.number}: "/evaluate" comes from someone who cannot use the AI quota; ignored`);
    return;
  }

  const reply = (body: string) => ctx.octokit.rest.issues.createComment({ ...ctx.repo, issue_number: issue.number, body });
  if (!ctx.config.ai.enabled) {
    await reply('AI evaluation is off. Set `ai.enabled: true` in `job-radar.config.yml` to use `/evaluate`.');
    return;
  }
  if (!options.ai) {
    await reply('AI evaluation is on, but the workflow gave job-radar no `models-token` or `profile`. See the README for the `evaluate` workflow.');
    return;
  }

  const { company, role } = splitTitle(issue.title);
  const description = descriptionOf(issue.body);
  if (!description.trim()) {
    await reply('This issue has no posting text to evaluate (jobs entered by hand and imported ones carry none). Paste the description in a comment and use a new issue, or open the link and judge it yourself.');
    return;
  }
  try {
    const evaluation = await evaluateJob(options.ai.client, options.ai.profile, {
      title: role,
      company,
      locations: [],
      description,
    });
    await reply(render(evaluation, ctx.config.ai.model));

    const labels = (issue.labels ?? []).map((label) => (typeof label === 'string' ? label : label.name));
    for (const name of labels.filter((label) => label.startsWith(FIT_PREFIX))) await removeLabel(ctx.octokit, ctx.repo, issue.number, name);
    await addLabels(ctx.octokit, ctx.repo, issue.number, [`${FIT_PREFIX}${evaluation.fit}`]);
    ctx.log.info(`Issue #${issue.number}: evaluated, fit ${evaluation.fit}/5`);
  } catch (error) {
    const message =
      error instanceof AiQuotaError
        ? 'The free GitHub Models quota is used up for now. Try `/evaluate` again later.'
        : `The evaluation failed: ${(error as Error).message}.`;
    await reply(message);
    ctx.log.warn(`Issue #${issue.number}: ${message}`);
  }
}
